    private val glyphs: Map<Char, Glyph> = parse()

    private fun parse(): Map<Char, Glyph> {
        val out = HashMap<Char, Glyph>()
        for (line in DATA.lines()) {
            if (line.isBlank()) continue
            val parts = line.split(' ')
            val c = parts[0].single()
            val rows = parts.drop(1)
            require(rows.size in CAP_HEIGHT..HEIGHT && rows.all { it.length == 5 }) { "Bad glyph '$c'" }
            val cols = IntArray(5) { x -> rows.indices.fold(0) { m, r -> if (rows[r][x] == '#') m or (1 shl r) else m } }
            val first = cols.indexOfFirst { it != 0 }
            val last = cols.indexOfLast { it != 0 }
            out[c] = Glyph(if (first < 0) IntArray(0) else cols.copyOfRange(first, last + 1))
        }
        return out
    }

    fun glyph(c: Char): Glyph? = if (c == ' ') null else glyphs[c] ?: glyphs['?']

    /** Width in font pixels of [text] at scale 1, with [GAP] columns between characters. */
    fun width(text: String): Int {
        var w = 0
        text.forEachIndexed { i, c ->
            if (i > 0) w += GAP
            w += glyph(c)?.width ?: SPACE_WIDTH
        }
        return w
    }

    fun covers(c: Char) = c == ' ' || glyphs.containsKey(c)
}
