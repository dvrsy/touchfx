android {
    namespace = "app.touchfx"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.touchfx"
        minSdk = 29          // Android 10: needed to capture music played on the phone
        targetSdk = 35
        versionCode = 2
        versionName = "0.2.0"
    }

    // Release signing reads keystore.properties (not committed):
    //   storeFile=C:/path/to/release.jks
    //   storePassword=...   keyAlias=...   keyPassword=...
    val keystoreProps = rootProject.file("keystore.properties")
    val releaseSigning = if (keystoreProps.exists()) {
        val props = Properties().apply { keystoreProps.inputStream().use { load(it) } }
        signingConfigs.create("release") {
            storeFile = file(props.getProperty("storeFile"))
            storePassword = props.getProperty("storePassword")
            keyAlias = props.getProperty("keyAlias")
            keyPassword = props.getProperty("keyPassword")
        }
    } else null

    buildTypes {
        // Debug builds get their own package so they install next to a release APK
        // (different signatures would otherwise block the install).
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"))
            if (releaseSigning != null) signingConfig = releaseSigning
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
